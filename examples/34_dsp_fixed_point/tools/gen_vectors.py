#!/usr/bin/env python3
"""Make the test vectors for 34_dsp_fixed_point.

This is the "reference": a 31-tap low-pass FIR filter written in plain numpy float math.
It also contains a bit-exact model of the integer (Q15) code that runs on the ESP32.
The C code must match the model exactly, and stay close to the float result.

Run:  python tools/gen_vectors.py        (needs numpy only)
It writes main/dsp_vectors.h. Commit that file; the build does not need Python.
"""
import pathlib
import numpy as np

TAPS = 31
CUTOFF = 0.10          # cutoff as a fraction of the sample rate
N = 1024               # samples in the test block
Q = 15                 # fractional bits (Q15: int16 with 15 fraction bits)

out_path = pathlib.Path(__file__).resolve().parent.parent / "main" / "dsp_vectors.h"


def design_lowpass(taps: int, cutoff: float) -> np.ndarray:
    """Windowed-sinc low-pass with a Hamming window, scaled for a DC gain of 1."""
    n = np.arange(taps) - (taps - 1) / 2
    h = 2 * cutoff * np.sinc(2 * cutoff * n) * np.hamming(taps)
    return h / h.sum()


def q15(x: np.ndarray) -> np.ndarray:
    """Round to Q15 and clip to the int16 range."""
    return np.clip(np.round(x * (1 << Q)), -32768, 32767).astype(np.int64)


h_float = design_lowpass(TAPS, CUTOFF)
h_q15 = q15(h_float)

# Test signal: a wanted tone (0.02 fs), an unwanted tone (0.35 fs) and a little noise.
rng = np.random.RandomState(1)
t = np.arange(N)
x_float = (0.40 * np.sin(2 * np.pi * 0.02 * t)
           + 0.30 * np.sin(2 * np.pi * 0.35 * t)
           + 0.02 * rng.randn(N))
x_q15 = q15(x_float)
x_in = x_q15.astype(np.float64) / (1 << Q)   # the filter input, exactly as the chip sees it

# Float reference: full-precision coefficients, zero start state, same length as the input.
y_ref = np.convolve(x_in, h_float)[:N] * (1 << Q)
y_ref_q15 = np.clip(np.round(y_ref), -32768, 32767).astype(np.int64)

# Bit-exact model of the C code: 32-bit accumulate, add half an LSB, shift, saturate.
acc = np.convolve(x_q15, h_q15)[:N]
y_model = np.clip((acc + (1 << (Q - 1))) >> Q, -32768, 32767).astype(np.int64)

err = np.abs(y_model - y_ref)
assert np.abs(acc).max() < 2**31, "accumulator would overflow int32"
print(f"taps={TAPS} samples={N}")
print(f"sum|h_q15| = {np.abs(h_q15).sum()} (must stay below 65536 for the int32 accumulator)")
print(f"max |model - float ref| = {err.max():.2f} LSB, mean = {err.mean():.3f} LSB")


def c_array(name: str, ctype: str, values) -> str:
    rows = []
    for i in range(0, len(values), 12):
        rows.append("    " + ", ".join(str(int(v)) for v in values[i:i + 12]))
    return f"static const {ctype} {name}[{len(values)}] = {{\n" + ",\n".join(rows) + ",\n};\n"


text = f"""/* Generated by tools/gen_vectors.py. Do not edit by hand. */
#pragma once
#include <stdint.h>

#define DSP_TAPS    {TAPS}
#define DSP_SAMPLES {N}

/* Filter coefficients: the same filter in float and in Q15. */
{c_array("DSP_COEF_Q15", "int16_t", h_q15)}
{c_array("DSP_COEF_F32_E9", "int32_t", np.round(h_float * 1e9))}
/* Input block, Q15. */
{c_array("DSP_INPUT_Q15", "int16_t", x_q15)}
/* Float reference output, rounded to Q15. */
{c_array("DSP_REF_Q15", "int16_t", y_ref_q15)}
/* Bit-exact model of the integer code. The C output must equal this. */
{c_array("DSP_MODEL_Q15", "int16_t", y_model)}
/* Largest allowed gap between the integer output and the float reference, in LSB. */
#define DSP_MAX_ERR_LSB {int(np.ceil(err.max())) + 1}
"""
out_path.write_text(text, encoding="utf-8", newline="\n")
print(f"wrote {out_path}")
